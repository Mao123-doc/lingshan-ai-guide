/** Real Express + production frontend smoke. Uses isolated data and no paid APIs. */
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createServer } = require('node:http');
const root = path.resolve(__dirname, '..');
require('node:module').createRequire(path.join(root, 'backend/package.json'))('tsx/cjs');
const { chromium } = require(path.join(root, 'frontend/node_modules/playwright'));

(async () => {
  const dataRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'lingshan-restored-'));
  process.env.DATA_ROOT = dataRoot;
  process.env.ADMIN_PASSWORD = 'isolated-runtime-password';
  process.env.ADMIN_USERNAME = 'admin';
  process.env.SECRET_KEY = 'isolated-runtime-key-not-a-production-credential';
  process.env.VECTOR_SERVICE_URL = 'http://127.0.0.1:1';
  for (const key of ['DEEPSEEK_API_KEY', 'AGNES_API_KEY', 'VISION_API_KEY', 'VISION_MODEL', 'VISION_BASE_URL']) delete process.env[key];
  fs.cpSync(path.join(root, 'data/route'), path.join(dataRoot, 'route'), { recursive: true });
  fs.cpSync(path.join(root, 'data/raw'), path.join(dataRoot, 'raw'), { recursive: true });
  const { createApp } = require(path.join(root, 'backend/src/app'));
  const { attachOperationsSocket } = require(path.join(root, 'backend/src/services/operations-socket'));
  const server = createServer(createApp());
  const hub = attachOperationsSocket(server);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch({ headless: true, args: ['--enable-unsafe-swiftshader'] });
  const context = await browser.newContext({ permissions: ['geolocation'], geolocation: { latitude: 31.4219, longitude: 120.0972 }, viewport: { width: 1280, height: 900 } });
  const page = await context.newPage();
  const errors = []; const warnings = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', event => { if (event.type() === 'warning' && event.text().includes('Live2D')) warnings.push(event.text()); });
  const evidence = { origin, mode: 'real-express-production-ui-models-disabled', checks: [] };
  try {
    await page.goto(`${origin}/qa`);
    await page.getByRole('button', { name: /发.*送/ }).waitFor();
    await page.getByPlaceholder(/想问什么/).fill('灵山大佛有多高？');
    await page.getByRole('button', { name: /发.*送/ }).click();
    await page.getByRole('button', { name: '查看回答依据' }).waitFor();
    await page.getByRole('button', { name: '提交评价' }).click();
    await page.getByText('评价已保存', { exact: true }).waitFor();
    assert.equal(JSON.parse(fs.readFileSync(path.join(dataRoot, 'feedback.json'))).length, 1);
    evidence.checks.push('stream-completion-with-evidence-and-persisted-feedback');
    await page.getByRole('button', { name: '查看附近' }).click();
    await page.getByText(/已获取定位/).waitFor();
    evidence.checks.push('real-nearby-api-with-browser-geolocation');
    await page.locator('input[aria-label="上传景点图片"]').setInputFiles(path.join(root, 'frontend/src/assets/character-portrait.png'));
    await page.getByText('视觉识别未配置', { exact: true }).waitFor();
    evidence.checks.push('unconfigured-vision-is-explicit-error');
    await page.waitForFunction(() => document.querySelector('.dh-char__live2d canvas') && !document.querySelector('.dh-char__img'), { timeout: 15000 });
    evidence.checks.push('actual-live2d-model-rendered-without-static-fallback');
    const out = path.join(root, 'output/competition-runtime'); fs.mkdirSync(out, { recursive: true });
    await page.screenshot({ path: path.join(out, 'qa.png'), fullPage: true });
    await page.locator('.dh-char__live2d canvas').screenshot({ path: path.join(out, 'live2d.png') });
    await page.goto(`${origin}/admin/login`);
    await page.getByPlaceholder('用户名').fill('admin'); await page.getByPlaceholder('密码').fill('isolated-runtime-password');
    await page.getByRole('button', { name: /登.*录/ }).click();
    await page.getByText('知识库管理', { exact: true }).waitFor();
    await page.getByRole('button', { name: '运营看板', exact: true }).click();
    await page.getByText('满意度', { exact: true }).waitFor();
    await page.waitForFunction(() => document.body.innerText.includes('100'));
    evidence.checks.push('real-admin-dashboard-feedback-stats');
    await page.goto(`${origin}/admin/digital-human`);
    await page.getByRole('button', { name: '保存配置', exact: true }).click();
    await page.getByText('数字人配置已保存', { exact: true }).waitFor();
    assert.equal(JSON.parse(fs.readFileSync(path.join(dataRoot, 'dh_config.json'))).style_preset, 'zen_red_gold');
    evidence.checks.push('real-persistent-digital-human-config');
    await page.goto(`${origin}/recommend`);
    await page.getByText(/路网缓存 v2/).waitFor();
    await page.evaluate(() => navigator.serviceWorker.ready);
    await page.reload();
    await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
    await context.setOffline(true);
    await page.reload();
    await page.getByRole('button', { name: '离线应急规划', exact: true }).click();
    await page.getByText('离线应急规划结果：使用缓存数据，未核验实时开放或道路条件。', { exact: true }).waitFor();
    await page.getByRole('img', { name: '按登记坐标绘制的路线示意图' }).waitFor();
    evidence.checks.push('offline-reload-and-local-return-route-solver');
    await page.screenshot({ path: path.join(out, 'offline-route.png'), fullPage: true });
    await context.setOffline(false);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`${origin}/qa`);
    await page.getByRole('button', { name: '语音输入' }).waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth) <= 1);
    evidence.checks.push('mobile-390px-no-horizontal-overflow');
    assert.deepEqual(errors, []);
    evidence.pageErrors = errors; evidence.live2dWarnings = warnings;
    fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(evidence, null, 2));
    console.log(JSON.stringify(evidence, null, 2));
  } finally {
    await browser.close(); hub.clients.forEach(socket => socket.terminate());
    await new Promise(resolve => hub.close(resolve)); server.closeAllConnections();
    await new Promise(resolve => server.close(resolve));
    const resolved = path.resolve(dataRoot);
    if (resolved.startsWith(path.resolve(os.tmpdir()) + path.sep) && path.basename(resolved).startsWith('lingshan-restored-')) fs.rmSync(resolved, { recursive: true, force: true });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
