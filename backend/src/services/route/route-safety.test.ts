import assert from 'node:assert/strict';
import { SceneStateSchema } from '../scene/scene-state';
import { loadRouteGraph } from './route-contract';
import { planRoute } from './route-planner';
import { validateRoute } from './route-validator';
const graph = loadRouteGraph();
const scene = (extra: Record<string, unknown> = {}) => SceneStateSchema.parse({ currentLocation:'south_gate', currentTime:'09:00', remainingMinutes:180, mobility:'normal', interests:[], mustVisitSpotIds:[], preferredPerformanceIds:[], visitedSpotIds:[], missingCriticalFields:[], returnToExit:true, ...extra });
const roundTrip = planRoute(scene(), graph);
assert.equal(roundTrip.feasible, true);
assert.equal(roundTrip.steps.at(-1)?.spotId, 'south_gate');
assert.equal(roundTrip.steps.at(-1)?.reasonCode, 'return_to_exit');
assert.ok(roundTrip.totalMinutes <= 180);
assert.equal(validateRoute(roundTrip, scene(), graph).valid, true);
assert.equal(roundTrip.distanceMeters, roundTrip.steps.reduce((sum, step) => sum + (step.distanceMeters || 0), 0));
assert.ok(roundTrip.steps.every(step => step.pathEvidence?.every(edge => graph.edges.some(real => JSON.stringify(real) === JSON.stringify(edge)))));
const impossible = planRoute(scene({remainingMinutes:20,mustVisitSpotIds:['LS-003']}),graph,1);
assert.equal(impossible.feasible,false);
assert.ok(!impossible.steps.some(step => step.spotId === 'LS-003'));
const performance = graph.performances[0];
const start = performance.start_times[0];
const [h,m] = start.split(':').map(Number);
const clock = (minutes:number) => `${String(Math.floor(minutes/60)).padStart(2,'0')}:${String(minutes%60).padStart(2,'0')}`;
const exact = scene({ currentLocation:performance.location_id, currentTime:clock(h*60+m-15), remainingMinutes:240, preferredPerformanceIds:[performance.id], preferredPerformanceTimes:{[performance.id]:start} });
const onTime = planRoute(exact,graph);
const show = onTime.steps.find(step => step.performanceId === performance.id);
assert.ok(show);
assert.equal(show.waitingMinutes,15); // Check-in is contained in waiting, not charged twice.
assert.equal(onTime.totalMinutes,onTime.walkingMinutes+onTime.visitingMinutes+onTime.waitingMinutes);
const late = planRoute({...exact,currentTime:clock(h*60+m-14)},graph);
assert.ok(!late.steps.some(step => step.performanceId === performance.id));
const tooShort = planRoute({...exact,remainingMinutes:15},graph);
assert.ok(!tooShort.steps.some(step => step.performanceId === performance.id));
assert.equal(SceneStateSchema.safeParse({...exact,remainingMinutes:-1}).success,false);
const changed = structuredClone(roundTrip); changed.steps[0].arrive='08:59';
assert.ok(validateRoute(changed,scene(),graph).violations.some(v=>v.code==='travel_time_axis_mismatch'));
const missingReturn=structuredClone(roundTrip);missingReturn.steps.pop();
assert.ok(validateRoute(missingReturn,scene(),graph).violations.some(v=>v.code==='missing_return_to_exit'));
const progress=planRoute(scene({currentLocation:'LS-003',currentTime:'10:00',remainingMinutes:80,visitedSpotIds:['LS-003'],mustVisitSpotIds:['LS-003']}),graph);
assert.equal(progress.feasible,true);
assert.ok(!progress.steps.some(step=>step.spotId==='LS-003'&&step.reasonCode!=='return_to_exit'));
assert.ok(progress.totalMinutes>=0 && progress.totalMinutes<=80);
console.log('Strict return, progress, provenance, conservation and check-in safety tests passed');
const laterGraph = structuredClone(graph);
laterGraph.performances[0].start_times = [start, clock(h*60+m+60)];
const unspecified = { ...exact, currentTime:clock(h*60+m-14), preferredPerformanceTimes:undefined };
assert.equal(planRoute(unspecified,laterGraph).steps.find(step=>step.performanceId===performance.id)?.performanceStartTime,clock(h*60+m+60));
assert.ok(!planRoute({...unspecified,preferredPerformanceTimes:{[performance.id]:start}},laterGraph).steps.some(step=>step.performanceId===performance.id));
